import { spawnSync } from 'node:child_process';
import { cpSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
if (path.basename(root) !== 'mobile-app') throw new Error('Разместите исходники в mobile-app/ серверного репозитория.');
const build = spawnSync(process.execPath, [path.join(root, 'node_modules/expo/bin/cli'), 'export', '--platform', 'web', '--output-dir', 'dist-auth-web'], { cwd: root, env: { ...process.env, PADEL_WEB_BASE_PATH: '/app' }, stdio: 'inherit' });
if (build.status !== 0) process.exit(build.status ?? 1);
const target = path.resolve(root, '../src/main/resources/static/app');
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
cpSync(path.join(root, 'dist-auth-web'), target, { recursive: true });
